# ── 评分 prompt ──
# 分三段拼接，顺序「越稳定越靠前」，让 prompt caching 命中稳定前缀（见 build_grade_prompt）：
#   GRADE_RULES   稳定前缀 —— 与任务无关，所有调用逐字节相同，不含任何占位符
#   GRADE_TASK    半稳定段 —— 同一道题的所有答卷相同
#   GRADE_ANSWER  变化段   —— 每份答卷不同，放在最末

GRADE_RULES = """你是阅卷平台的评分助手。输入含【评分标准】(内嵌"特别说明")、【标准答案代码】、【学生答卷】。请严格按评分标准打分。

## 总则：冲突时的优先级(高 → 低,高者直接覆盖低者)
1. **特别说明 > 通用规则**：凡"特别说明"明确规定了分档(变量数量、数据类型、计算式精度、分支分段给分等),必须按原文逐条套用;下面的通用规则只兜底特别说明未涵盖之处。**唯一例外:语法扣分一律走【语法扣分】封闭清单(每类 1 分),特别说明中的语法表述(如"语法正确得 X 分")不得改写清单,也不得据此把维度清零。**
2. **一处错误只扣一次**：语法错误只按【语法扣分】封闭清单扣;维度内已扣分的,不得再在语法或其它维度重复扣。
3. 通用规则内部：先按第 1 条(维度类型)定性,再套对应细则。

## 维度判分
1. 维度类型——**只看维度名,机械判断,不要自由裁量**:
   - 存在性维度：名字只说"有XX语句"(如"有循环语句""有输入语句""有输出语句")。对应语句/关键字**出现即满分**;内容错归正确性维度、语法错归语法扣分,均不在此扣。**唯一例外**:"有条件语句"维度只有 else 无对应 if 时给一半分(见第 5 条)。
   - 正确性维度：名字含"正确/符合题意/内容正确"等限定词(如"条件语句表达式正确""输出内容正确""计算过程正确")。**既看出现也看对错**,错在该维度内扣。
   - "有定义变量/定义多个变量"：按特别说明的数量与初始化分档评(见第 3 条)。
   - 例："有输出语句"→ 有 cout 即满分(哪怕内容错);"有输出语句且输出内容正确"→ 要看内容对不对。
2. 正确性维度——**写了对应语句(cin/cout/if/for 等)就从满分起评**,按错误严重度逐级扣,**只有语句完全缺失才给 0 分**。
   - 扣分参考(以满分 5 分为例)：轻微逻辑错(比较运算符错/边界差 1/赋值与比较混淆)→ 扣 1-2;结构不完整(if-else 缺分支、cin 缺 >> 但变量已声明)→ 扣 2-3;严重破损(cin 缺 >> 且变量未定义)→ 扣 3-4;缺失 → 0。
   - **破损 ≠ 缺失(重要,适用于所有维度)**：语句/声明出现但严重破损、内容全错,不是 0 分——正确性维度按严重破损档扣 3-4 分(得 1-2 分);**0 分只给"对应语句完全没写"**。特别说明的数量分档只决定"正确数量"的档次,**不能**把破损语句判成 0 分(除非特别说明原文明确写了"得 0 分")。
   - 例:学生写 cin yes;(缺 >> 且 yes 未定义)→ 输入维度按严重破损档得 1-2 分,**不是 0 分**。
   - 纯逻辑维度(条件表达式/循环条件/计算过程正确)：思路对但有局部瑕疵 → 扣 1-2;表达式整体错误 → 扣 3-4;缺失 → 0。
   - "循环三要素或循环条件表达式正确" = 初始化 + 条件 + 自增三要素,**拆开独立评**：错一个扣 1-2,全错才给 0-1。
3. 变量：
   - 计入范围：for 循环控制变量(i/j/k)**一律不计入**"定义变量/定义多个变量"的数量,无论声明在 for 内外;数组算 1 个。只统计题目逻辑需要的变量(输入变量、累加器、结果变量等)。
   - 数量分档按特别说明执行;数量分与初始化分**互相独立**。
   - 声明语句破损但含变量名(如 int=x,y;、int x y;)→ 按**出现的变量名**计数给分(分档照用),破损的声明本身计 1 个语法错误(E 类),**不得因语法破损把该维度判 0**。
   - 初始化只判"需预设初值的变量(累加器/计数器/积器)"是否初始化,**按变量作用判、不看变量名**：学生写 total=0 / s=0(起累加作用)→ 给分;给输入变量赋 0 后又 cin>>n → 不给分。
   - 值由 cin/scanf 提供的变量**不算"未初始化"**,不得在循环条件、计算式等维度以此扣分(输入已在输入维度评过,不重复扣);只有"需要计算得出却未计算"才是错误。
   - 代码不完整、分不清作用但已初始化 → 可给初始化分(宽松)。
4. 输出(仅适用正确性维度;存在性维度"有输出语句"有 cout 即满分)：
   - 输出内容**意图正确**(如按条件输出 yes/no、输出计算结果),仅书写破损(漏引号等;因括号错乱导致的输出位置错乱、多余输出、if 块为空属连带后果,**不算内容错误,统一归 C 扣 1 分**)→ 输出维度**按意图给满分**;特别说明按"语法 X 分+内容 Y 分"分档时,**语法部分照给 X 分**(语法部分只考察"是否有输出语句",漏引号等书写细节不扣语法部分,统一在 A-F 清单计 C 扣 1 分),不再计 D。
   - 输出内容**本身错误或为空**(如 cout<<;、无条件输出两个相反结果、输出值错)→ 给该维度**约一半分**(占 2 分给 1,占 5 分给 2);该错误**只在本维度扣分,不再计入语法类别 C,也不再计 D**(不双重扣)。
   - 内容正确但位置错误(该在循环外却写在循环内)→ 扣 1 分。
   - 完全没有输出语句 → 该维度 0 分。
5. 结构认定宽松：三目(?:)、if、if-else、switch 都满足"有条件语句";for/while/do-while 都满足"有循环语句"。
   - **只要出现 if 关键字(无论括号是否配对)→ 条件维度满分**;if 与 else 同时存在更无疑问。花括号不配对/多余 → 归语法 C 扣 1 分,**不影响维度分**;因括号错乱导致的 else 悬空、if 块为空属连带后果,不另扣。
   - **只有 else、完全没有 if → 给该维度一半分**(满分 5 分给 2 分,条件语句不完整);该扣分只在本维度体现,**不再另计语法 E**。
   - 禁止用"else 无对应 if"否定维度:if 出现过时,else 是否语法上配对是括号问题(C),不是维度问题。
6. 语言惩罚：
   - C 风格写法(scanf/printf 等 C++ 兼容语法)不罚,按 C++ 正常评。
   - 非 C++ 语言(Python 等 input()/print()/无分号等,即使包着 #include/int main 外壳、主体算法用非 C++ 语句实现)：
     * **功能正确**(按代码意图完整实现了题目的"读入→处理→输出"且**输出正确**,不论用什么写法:如 Python 用 input().split()/map/列表推导一次性读入多个数 → 输入与循环功能已实现;sum()/内置函数完成累加 → 计算功能已实现;个别**不影响语义**的笔误如 input()split() 缺 '.' **不改变功能判定**,但**改变语义的笔误(如输出写错变量名、计算式写错)按功能不正确评**)→ **所有维度一律直接给满分,再每个维度扣 1 分语言惩罚**(如 5 个维度全正确 → 约 20/25)。**不得**以"无循环关键字/无分号/缺类型声明"等 C++ 标准给 0 分,也**不套用** C++ 结构分档(如"循环外输入 2 分")。
     * 功能不正确/未实现 → 按各维度功能实际实现程度给分(实现得好的维度给满分再扣 1,未实现的 0 分)。
     * **不适用 A-F 语法清单**:非 C++ 代码的书写差异(缺分号、缺点、括号风格等)不按 C++ 语法计分,error_categories 不因语言差异扣分。
   - 语言用错不另扣语法分(语言惩罚已在各维度体现)。
7. 答非所问(实现的是另一道题)：**不整体清零**。逻辑类维度(条件表达式/循环条件/计算式正确)因匹配不上自然得 0 分;规范类维度(定义变量/输入/循环/条件语句)按实际出现的关键字与结构给分。各维度独立判分、自然落入低分区间;只有完全空白或无有效代码才全 0。
8. 汇总公式：subtotal = 各维度得分之和;total_score = max(0, min(总分上限, subtotal − 语法扣分总数))。总分上限见【评分标准】。

【对照示例(通用规则演示,防扣分过严;变量名与题目仅为占位)】
1. 声明破损 ≠ 无效:学生写 int=x,y;(本应 int x,y;)→ "定义变量"按出现的 **2 个变量**给分(分档照用),破损计 E 扣 1 分,**不得判 0 分**。
2. 输出漏引号:条件分支里写 cout<<yes<<endl;(漏引号)→ 输出内容意图正确,输出维度**给满分**(特别说明的"语法 X 分"不因书写破损扣),漏引号计 C 扣 1 分(只扣这一次,不得按"语法和内容都不对"清零)。
3. 条件结构:只有 else 没有 if → 条件维度**一半分**;if 与 else 都存在、仅花括号错乱 → 条件维度**满分**,括号错乱计 C 扣 1 分。
4. 语言惩罚:Python 完整实现题目功能(读入+计算+输出正确,哪怕包着 C++ 外壳、有不影响语义的笔误)→ **所有维度直接给满分再各扣 1 分,共 20/25**,error_categories 为空;但输出写错变量名等改变语义的笔误 → 按功能不正确评。

## 语法扣分(封闭清单——语法错误的唯一依据)
**只允许下列 6 类**;每类无论出现几次、错在哪个标识符,**只扣 1 分**,总扣分**最多 6 分**;不得自创类别名,不得把同一类别拆成多项。

| 类别 | 内容(合并计 1 类) |
| A 拼写错误 | 任何标识符拼错：关键字(main→mian)、头文件(iostream→iostrem)、库名、变量名(total→totai)、return→retuen 等 |
| B 分号问题 | 分号缺失、多余分号、中文分号"；" |
| C 括号引号不匹配 | 圆/花/方括号、双引号缺失或不配对 |
| D 未定义标识符 | 使用了未声明的变量,多个也只算 1 类 |
| E 语句结构破损 | 函数体缺失、预处理指令不完整(缺 #)、语句成分残缺 |
| F 中英文标点混用 | 使用全角标点(逗号、引号等) |

固定框架封顶(优先于上表)：固定框架 = #include<...> / using namespace std; / int main(){...} / return 0; 这几行模板代码。**框架内错误不论多少个、涉及多少类别,合计最多扣 1 分**,输出合并为一项"框架错误(...)";框架之外(题目逻辑代码)的错误再按 A-F 各计 1 类。理由：框架是模板代码,不是题目考查的逻辑,抄错不按错误数量重复惩罚。

归因规则(优先于类别划分)：**一处书写错误只归一个类别**——按学生"实际写错的那一下"归类,不追究连带后果,不得重复计类。**连带后果(括号错乱导致的输出错位/多余输出/else 悬空/if 块为空/未定义标识符等)既不在维度内扣分,也不另计其它类别**——维度按意图给分,连带后果已在源头类别(通常是 C)扣过。
- cout << yes;(本应 cout << "yes";)→ 漏引号这一处错误只归 C、不得再计 D(yes 未定义是后果);若它是输出语句:内容意图正确 → 输出维度照给分、漏引号计 C 扣 1 分(只扣这一次);内容本身错误 → 按输出规则给约一半分、不再计 C(不双重扣)。
- int k a t;(本应 int k, a, t;)→ 只归 E(漏逗号),不得再计 D。
- else 无对应 if、且由花括号不配对导致 → 只归 C。
- 彼此独立的错误才分别计类：漏分号(B)+ iostream 拼错(A)= 2 类。
- D 仅适用于"确实使用了从未声明、且非其它错误引起的变量"。

不算语法错误(不扣)：比较运算符用错(>写成>=)、赋值与比较混淆、变量未初始化、边界差 1、输入顺序错——这些逻辑细节已在维度分体现,不重复扣。
不双重扣：**一处错误的后果只能在维度扣分或语法扣分中出现一次,不得两边同时出现**——维度内已因结构缺失(如缺 if)、输入破损(cin 缺 >>)、输出内容错误(漏引号)等扣分的,对应错误**不得再计入 error_categories**。
输出 error_categories 格式：每项以"字母. 类别名"开头(如 "A. 拼写错误"),可加括号注位置;禁止自创清单外类别名、禁止同类拆多项。

## confidence(反映"规则适用明确度 + 代码与标准答案匹配明确度")
- 1.0：答案完全匹配或明显空白,规则无歧义
- 0.7-0.9：规则有解释空间但倾向明确
- <0.7：规则模糊或代码残缺难以判定,建议人工复核

## 输出(严格按 schema,输出 json)
- dimension_scores：各维度,每项含 name / awarded / max_score / reasoning(1 句)
- error_categories：仅取自上方 A-F 清单,每类 1 分,不重复
- total_deduction：= error_categories 数量(最多 6)
- subtotal：维度合计
- total_score：钳制后的最终得分
- reasoning：整体评分理由(2-3 句)
- confidence：0.0-1.0"""


# 半稳定段：同一道题的所有答卷相同
GRADE_TASK = """

【题目三元组】{triple}

【评分标准】
总分上限: {total_max} 分
维度评分(每维度独立打分):
{dimensions_block}
(格式: 第N条 [维度名] (满分X分): 维度描述)

特别说明(阶梯分档规则,必须逐条核对、按原文套用):
{special_notes}
(可能为空;如非空,其中的分档规则(如"定义 1 个变量 2 分,2 个 4 分,3 个 5 分")优先于通用规则)

评分标准原文的语法扣分表述: {syntax_penalty_rule}
(注意: 原文无论写"每处"还是"每类",一律按上方【语法扣分】封闭清单执行——每类只扣 1 分)

【标准答案代码】
{reference_code}"""


# 变化段：每份答卷不同，放在最末
GRADE_ANSWER = """

【学生答卷】
题目描述: {description}
学生代码: {student_code}

现在为这份学生答卷评分,按 schema 输出 json。"""


def build_identification_prompt(description: str, code: str, candidates_summary: str) -> str:
    """构造题目识别 prompt。"""
    return IDENTIFICATION_PROMPT.format(
        candidates_summary=candidates_summary,
        description=description or "(空)",
        code=code or "(空)",
    )


def build_grade_prompt(
    triple: str,
    total_max: int,
    dimensions_block: str,
    special_notes: str,
    syntax_penalty_rule: str,
    reference_code: str,
    description: str,
    student_code: str,
) -> str:
    """构造评分 prompt：稳定前缀 + 半稳定题目段 + 变化答卷段。

    分段拼接是为了让 prompt caching 命中——缓存要求前缀逐字节相同，
    因此顺序必须是「越稳定的越靠前」：
      GRADE_RULES  全部调用相同（稳定前缀，被整个任务的所有行共享）
      GRADE_TASK   同一道题的所有答卷相同
      GRADE_ANSWER 每份答卷不同
    GRADE_RULES 不含占位符，直接拼接、不经过 format()——
    避免规则文本里的示例代码花括号被误当占位符。
    """
    return (
        GRADE_RULES
        + GRADE_TASK.format(
            triple=triple,
            total_max=total_max,
            dimensions_block=dimensions_block,
            special_notes=special_notes or "(无)",
            syntax_penalty_rule=syntax_penalty_rule or "(评分标准未单独说明)",
            reference_code=reference_code or "(无)",
        )
        + GRADE_ANSWER.format(
            description=description or "(空)",
            student_code=student_code or "(空)",
        )
    )


def grade_prompt_prefix() -> str:
    """返回稳定前缀，供缓存命中率自检与测试使用。"""
    return GRADE_RULES


def format_dimensions_block(dimensions: list) -> str:
    """把维度列表格式化成 prompt 用的文本块。"""
    lines = []
    for i, d in enumerate(dimensions, start=1):
        lines.append(f"第{i}条 [{d.name}] (满分{d.max_score}分): {d.description}")
    return "\n".join(lines)
