"""Prompt 模板：题目识别 + 评分。

针对 DeepSeek 优化（中文 prompt，结构化输出走 with_structured_output）。
PRD §8 的完整草案。
"""
from __future__ import annotations

# ── 题目识别 prompt ──

IDENTIFICATION_PROMPT = """你是阅卷平台的题目识别助手。下面是一次阅卷任务中从学生答卷 URL 抓取到的【题目描述】和【学生代码】。
任务文件夹内共有若干道参考题(标准答案已知),按"级别(一级/二级)× 场次(上午/下午) × 题号(1/2)"组织。
请判断这份答卷属于这些参考题中的哪一道。

判断依据(按优先级):
1. 题目描述的题意(输入输出要求、计算逻辑)——最主要依据。
2. 学生代码的算法结构与标准答案的匹配度。
3. 不要根据变量名、注释、代码风格判断;只看算法意图和题意。

【候选参考题清单】
{candidates_summary}
(每条含:候选编号、级别/场次/题号、标准答案代码)

【待识别答卷】
题目描述:
{description}

学生代码:
{code}

请输出 json:
- level: "L1" 表示一级, "L2" 表示二级
- session: "morning" 表示上午场, "afternoon" 表示下午场
- question: 题号 1 或 2
- confidence: 置信度 0.0-1.0(0.9+题意明确匹配;0.7-0.9算法匹配但有歧义;<0.7不确定)
- reasoning: 1-2句说明判断依据,若置信度<0.9需说明歧义点"""


# ── 评分 prompt ──

GRADE_PROMPT = """你是阅卷平台的评分助手。下面是一道题的【评分标准】、【标准答案代码】、【学生答卷的题目描述和学生代码】。
请严格按照评分标准打分。

【题目三元组】{triple}

【评分标准】
总分上限: {total_max} 分
维度评分(每维度独立打分):
{dimensions_block}
(格式: 第N条 [维度名] (满分X分): 维度描述)

特别说明(阶梯分档规则,必须逐条核对):
{special_notes}
(可能为空;若非空,含如"定义1个变量2分,2个4分,3个5分"这类分档规则,按学生代码实际写法套用)

语法扣分规则: {syntax_penalty_rule}
(即: 按错误类别扣分——拼写错误作为一个整体类别扣1分,分号缺失作为整体类别扣1分,括号不匹配扣1分等。每类错误只扣1分,不按出现次数重复扣。)

【标准答案代码】
{reference_code}

【学生答卷】
题目描述:
{description}

学生代码:
{student_code}

评分要求:
0. 规则优先级(最重要): 上方【评分标准】里的"特别说明"是本次任务的权威分档规则,优先级高于下面的通用规则。凡特别说明明确规定了某条维度的分档(如变量数量分档、数据类型要求、计算式精度要求、分支计算分段给分等),必须严格按特别说明原文套用,不要用下面的通用规则覆盖它。下面的通用规则只适用于特别说明未涵盖的情况。
1. 维度分类(按维度名机械判断,不要自由裁量):
   - 【存在性维度】维度名只说"有XX语句"、不含正确性限定词的(如"有循环语句""有条件语句(双if/if-else)""有输出语句""有输入语句""有输入输出语句"): 只看对应语句/关键字是否出现,出现即满分。语句内容对不对、语法错不错都不在此维度扣分(内容问题归"XX正确"类维度,语法问题归语法扣分)。
   - 【正确性维度】维度名含"正确""符合题意""内容正确"等限定词的(如"条件语句表达式正确""循环三要素或循环条件表达式正确""有输入语句正确""有输入语句，且正确输入多个变量""有输出语句且输出内容正确""输出语句符合题意""计算过程正确""使用正确的数据类型""程序框架正确"): 既看是否出现,也看正确性,错误在该维度内扣分。
   - 判断依据是维度名本身,不是你对题目的理解。例: "有输出语句"→有 cout 即满分(哪怕输出内容错);"有输出语句且输出内容正确"→要看内容对不对。
   - "有定义变量""定义多个变量"按特别说明的数量/初始化分档评(见第3、4条)。
2. 语句出现即从满分起扣(重要,适用于所有正确性维度——即维度名含"正确/符合题意/内容正确"等限定词的维度):
   - 核心原则: 学生写了对应语句(cin/cout/if/for等)就从满分开始评估,按错误严重程度在该维度内逐级扣分,不要因有错就直接给 0 分。只有语句完全缺失才给 0 分。
   - 扣分力度参考(以满分 5 分为例):
     · 轻微逻辑错误（如比较运算符错、边界差1、赋值与比较混淆） → 扣1-2分
     · 结构不完整(如if-else缺一个分支、cin缺 >> 但变量已声明) → 扣 2-3 分
     · 语句严重破损(如 cin 缺 >> 且变量未定义) → 扣 3-4 分
     · 语句完全缺失 → 0 分
   - 纯逻辑维度(条件语句表达式正确、循环三要素或循环条件表达式正确、计算过程正确等): 同样适用上述"从满分起扣"原则。整体思路正确但有局部瑕疵(比较运算符错、边界差 1、赋值比较混淆、初始化错等)从满分扣 1-2 分;表达式整体错误扣 3-4 分;缺失给 0 分。
   - 循环三要素要拆开评(重要): "循环三要素或循环条件表达式正确"维度含三个独立要素——初始化(i=1)、条件(i<=n)、自增(i++)。只错一个要素扣 1-2 分,三个要素全错才给 0-1 分。
   - 变量/输入/输出/数据类型维度的数量部分: 严格按特别说明的分档规则套用。
   - 特别说明有明确分档时,特别说明优先。特别说明没写分档的,按本条规则评。
3. 变量初始化判定(重要,避免不一致):
   - 初始化给分看"初始化的变量是否对应参考答案里需要初始化的变量"。需要初始化的变量指累加器(sum/count/total)、计数器、积器(ans/product)等需要预设初值的变量。
   - 按变量作用判定,不看变量名: 参考答案 int sum=0;,学生写 total=0 或 s=0(起累加器作用)→ 给初始化分;学生写 n=0 后又 cin>>n(n 是输入变量,初始化无意义)→ 不给初始化分。
   - 变量数量分与初始化分独立: 变量数量按特别说明的数量分档给分;初始化分按上述"是否初始化了需初始化的变量"判定。
   - 代码不完整无法分辨变量作用、但学生初始化了某变量 → 可给初始化分(宽松)。
   - 变量值由输入提供的不算"未初始化"(重要): 若某变量的值由 cin/scanf 输入语句提供(如 cin>>n 后 n 就有值),不要在循环条件、计算式等其他维度以"变量未初始化"为由扣分——输入环节已在输入维度评过分,不重复扣。只有当变量需要经过计算才能得出、而答卷没有做该计算时,才算真正的错误并扣分。
4. 变量计入范围(重要): 循环控制变量(for 里的计数器 i/j/k)一律不计入"定义变量""定义多个变量"维度的变量数量,无论它声明在 for 内部(for(int i=1;...))还是 for 外部(int i; for(i=1;...))。该维度只统计题目逻辑需要的变量(如输入变量 n/x、累加器 sum、结果变量等)。数组(如 int arr[n])算 1 个变量。
5. 输出内容给分(仅适用于【正确性维度】,即维度名含"正确/符合题意/内容正确"的输出维度;若是【存在性维度】"有输出语句"则有 cout 即满分,不适用本条):
   - 有输出语句(cout/printf)但输出内容错误或缺失(如 cout << ;): 按输出在该维度的占分给约一半——输出占 2 分给 1 分,占 5 分给 2 分。且不额外扣语法分。
   - 输出内容正确但位置错误(如该在循环外却写在循环内): 从该维度满分扣 1 分。
   - 完全没有输出语句: 输出部分给 0 分。
6. 拼写错误不双重扣(重要):
   - 所有拼写错误（含变量名、关键字）、分号缺失、括号不匹配、引号缺失等归为语法错误类别。
   - 每个错误类别只扣1分，无论出现次数。
   - 维度内不得因语法错误扣分；若维度内已因“结构缺失”扣分（如缺if），不再将该缺失视为语法错误（不重复扣）。
7. 结构认定宽松:
   - 三目运算符(?: :)、if 语句、if-else、switch 都算"有条件语句"维度满足。
   - for 循环、while 循环、do-while 都算"有循环语句"维度满足。
8. 语言惩罚(重要):
   - C 语言写法(scanf/printf 等 C++ 兼容语法)不扣语言惩罚,按 C++ 标准正常评。
   - Python/其他与 C++ 不兼容的语言(input()/print()/无分号/无类型声明等): 每个"有动作"的维度扣 1 分语言惩罚。"有动作"指该维度要求的语法结构出现(不管写得对不对、变量声明没)。没动作的维度本就 0 分,不重复扣。
   - 例: 学生用 Python 写了求和题,有 input/变量/for/print,逻辑完全正确 → 各有动作维度 5-1=4 分,合计约 20 分。
   - 语言用错不单独扣语法分(语言惩罚已在各维度体现)。
9. 答非所问(实现的是另一道题): 按踩分点独立判分,不要因"答非所问"就把所有维度清零。逻辑类维度(条件表达式正确、循环条件正确、计算式正确)因匹配不上自然得 0;规范类维度(有定义变量、有输入语句、有循环语句、有条件语句)按实际出现的关键字/结构给分。不设额外上限,各维度独立判分自然落到低分区间。完全空白或没写有效代码才全 0。
10. 语法扣分: 按错误类别识别,而非按出现次数。每类错误只扣 1 分,列出每个错误类别的名称。
   - 不算语法错误(不扣): 比较运算符用错(>写成>=)、赋值与比较混淆(=写成>=或==)、变量未初始化、边界差1、输入顺序错。这些是逻辑细节,已在相关维度部分分体现,不重复扣。
   - 算语法错误(每类1分): 关键字拼错(如 main 写成 mian)、分号缺失、括号不匹配、endl 误用为变量、字符串引号缺失、变量名拼写错(如 totai_water 应为 total_water、retuen 应为 return)等真正的语法/拼写错误。
11. 汇总: subtotal = 5维度之和; total_score = max(0, min({total_max}, subtotal - 语法扣分总数))。
12. confidence: 反映"评分规则适用明确度 + 学生代码与标准答案匹配明确度"。
   - 1.0: 答案完全匹配或明显空白,规则适用无歧义
   - 0.7-0.9: 评分规则有解释空间但倾向明确
   - <0.7: 评分规则模糊或学生代码部分完成难以判定,建议人工复核

输出结构(严格按 schema,输出 json):
- dimension_scores: 5个维度各自 {{name, awarded, max_score, reasoning}}
- error_categories: 语法错误类别列表(每个类别描述,每类1分)
- total_deduction: 语法扣分总数 = 类别数
- subtotal: 维度合计
- total_score: 钳制后的最终得分
- reasoning: 整体评分理由(2-3句)
- confidence: 0.0-1.0"""


def build_identification_prompt(description: str, code: str, candidates_summary: str) -> str:
    """构造题目识别 prompt。"""
    return IDENTIFICATION_PROMPT.format(
        candidates_summary=candidates_summary,
        description=description or "(空)",
        code=code or "(空)",
    )


def build_grade_prompt(
    triple: str,
    total_max: int,
    dimensions_block: str,
    special_notes: str,
    syntax_penalty_rule: str,
    reference_code: str,
    description: str,
    student_code: str,
) -> str:
    """构造评分 prompt。"""
    return GRADE_PROMPT.format(
        triple=triple,
        total_max=total_max,
        dimensions_block=dimensions_block,
        special_notes=special_notes or "(无)",
        syntax_penalty_rule=syntax_penalty_rule or "语法错误/拼写错误每处扣1分",
        reference_code=reference_code or "(无)",
        description=description or "(空)",
        student_code=student_code or "(空)",
    )


def format_dimensions_block(dimensions: list) -> str:
    """把维度列表格式化成 prompt 用的文本块。"""
    lines = []
    for i, d in enumerate(dimensions, start=1):
        lines.append(f"第{i}条 [{d.name}] (满分{d.max_score}分): {d.description}")
    return "\n".join(lines)
